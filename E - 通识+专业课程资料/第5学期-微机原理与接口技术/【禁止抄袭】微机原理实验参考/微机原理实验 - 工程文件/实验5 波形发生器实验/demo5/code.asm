;--- 寄存器定义 ---
DAC_PORT    EQU P0      ; DAC0832 数据口
SW_INPUT    EQU P1      ; P1.0-P1.3 为波形选择开关
LED_PORT    EQU P1      ; P1.4-P1.7 为波形指示灯
FREQ_PORT   EQU P2      ; 频率控制输入口

;--- 程序入口 ---
ORG 0000H
    LJMP START

ORG 0030H
START:
    ; 初始化
    MOV DAC_PORT, #80H  ; DAC输出中间值
    MOV P1, #0FFH       ; P1口置高：低4位做输入准备，高4位LED全灭(设LED低电平亮)
    
MAIN_LOOP:
    ; --- 流程图逻辑开始 ---
    
    ; 1. 检测方波开关 (P1.0)
    JB P1.0, CHK_SAW    ; 如果P1.0是高电平(未按下)，跳转检查锯齿波
    
    ; P1.0按下 (方波选择)
    CLR P1.4            ; 点亮方波指示灯 (P1.4)
    SETB P1.5           ; 熄灭其他灯
    SETB P1.6
    SETB P1.7
    LCALL WAVE_SQUARE   ; 调用方波子程序
    SJMP MAIN_LOOP      ; 执行完一周期后重新检测（实现循环）

CHK_SAW:
    SETB P1.4           ; 熄灭方波灯
    
    ; 2. 检测锯齿波开关 (P1.1)
    JB P1.1, CHK_TRI    ; 未按下，查三角波
    
    ; P1.1按下 (锯齿波选择)
    CLR P1.5            ; 点亮锯齿波指示灯
    SETB P1.6
    SETB P1.7
    LCALL WAVE_SAW      ; 调用锯齿波子程序
    SJMP MAIN_LOOP

CHK_TRI:
    SETB P1.5           ; 熄灭锯齿波灯
    
    ; 3. 检测三角波开关 (P1.2)
    JB P1.2, CHK_SINE   ; 未按下，查正弦波
    
    ; P1.2按下 (三角波选择)
    CLR P1.6            ; 点亮三角波指示灯
    SETB P1.7
    LCALL WAVE_TRI      ; 调用三角波子程序
    SJMP MAIN_LOOP

CHK_SINE:
    SETB P1.6           ; 熄灭三角波灯
    
    ; 4. 检测正弦波开关 (P1.3)
    JB P1.3, ALL_OFF    ; 未按下，去全灭逻辑
    
    ; P1.3按下 (正弦波选择)
    CLR P1.7            ; 点亮正弦波指示灯
    LCALL WAVE_SINE     ; 调用正弦波子程序
    SJMP MAIN_LOOP

ALL_OFF:
    SETB P1.7           ; 熄灭正弦波灯
    ; 如果没有按键按下，保持输出不变或输出0，这里选择循环检测
    SJMP MAIN_LOOP

;====================================================================
; 通用延时子程序 (频率控制)
; P2值越大 -> 频率越高 -> 延时越短    算法: 延时次数 = (255 - P2值)
;====================================================================
DELAY_FREQ:
    PUSH ACC            ; 保护累加器
    PUSH 07H            ; 保护R7
    
    MOV A, FREQ_PORT    ; 读取P2口频率设定值
    CPL A               ; 取反 (例如: P2=255(FF) -> A=0; P2=0 -> A=255)
    JZ DELAY_MIN        ; 如果结果为0，说明P2是255(最高频)，直接返回
    
    MOV R7, A           ; 将反码存入R7作为循环次数
DLY_LOOP:
    DJNZ R7, DLY_LOOP   ; 简单的软件延时循环
    
DELAY_MIN:
    POP 07H
    POP ACC
    RET

;====================================================================
; 1. 方波生成子程序（输出00H -> 延时 -> 输出FFH -> 延时）
; 与其他波形频率近似（每周期约256步），循环调用延时128次高电平/128次低电平
;====================================================================
WAVE_SQUARE:
    MOV R6, #128        ; 半周期计数
SQ_HIGH:
    MOV DAC_PORT, #0FFH ; 输出最大值
    LCALL DELAY_FREQ
    DJNZ R6, SQ_HIGH
    
    MOV R6, #128        ; 半周期计数
SQ_LOW:
    MOV DAC_PORT, #00H  ; 输出最小值
    LCALL DELAY_FREQ
    DJNZ R6, SQ_LOW
    RET

;====================================================================
; 2. 锯齿波生成子程序（0 -> 255, 步长2）
;====================================================================
WAVE_SAW:
    MOV A, #00H         ;以此为起点
SAW_LOOP:
    MOV DAC_PORT, A     ; 输出当前值
    LCALL DELAY_FREQ    ; 延时
    ADD A, #02H         ; 步长 +2
    JNZ SAW_LOOP        ; 如果没溢出回0，继续循环
    RET

;====================================================================
; 3. 三角波生成子程序（0 -> 254 (上升), 254 -> 0 (下降), 步长2）
;====================================================================
WAVE_TRI:
    MOV A, #00H         ; 起点
    
    ; 上升段 (0 -> 254)
TRI_UP:
    MOV DAC_PORT, A
    LCALL DELAY_FREQ
    ADD A, #02H
    CJNE A, #0FEH, TRI_CHK_UP ; 判断是否达到254 (0FEH)
    SJMP TRI_DOWN_START       ; 达到顶点，开始下降
TRI_CHK_UP:
    JC TRI_UP                 ; 如果A < FE，继续上升
    
    ; 下降段 (254 -> 0)
TRI_DOWN_START:
    MOV A, #0FEH
TRI_DOWN:
    MOV DAC_PORT, A
    LCALL DELAY_FREQ
    CLR C
    SUBB A, #02H
    JNZ TRI_DOWN        ; 直到减到0
    MOV DAC_PORT, A     ; 输出最后的0
    LCALL DELAY_FREQ
    RET

;====================================================================
; 4. 正弦波生成子程序 (查表法)
; 逻辑: 查表输出0-255个点
;====================================================================
WAVE_SINE:
    MOV DPTR, #SINE_TABLE ; 指向表头
    MOV R6, #0            ; 计数器 0-255
SINE_LOOP:
    MOV A, R6
    MOVC A, @A+DPTR       ; 查表
    MOV DAC_PORT, A       ; 输出
    LCALL DELAY_FREQ
    INC R6
    MOV A, R6
    JNZ SINE_LOOP         ; 循环256次
    RET

